/** Поиск по урокам: слова запроса сравниваются с названием, текстом, шагами и советами (допускаются опечатки). */
fun searchLessons(all: List<Lesson>, query: String): List<Lesson> {
    val tokens = SearchLogic.words(query)
    if (tokens.isEmpty()) return all
    return all.mapNotNull { l ->
        val hay = SearchLogic.words(l.title + " " + l.body + " " + l.steps.joinToString(" ") + " " + l.tips.joinToString(" "))
        val per = tokens.map { t -> hay.maxOfOrNull { SearchLogic.wordScore(t, it) } ?: 0 }
        if (per.all { it > 0 }) l to per.sum() else null
    }.sortedByDescending { it.second }.map { it.first }
}

fun searchFaq(query: String): List<Faq> {
    val tokens = SearchLogic.words(query)
    if (tokens.isEmpty()) return FAQ
    return FAQ.mapNotNull { f ->
        val hay = SearchLogic.words(f.q + " " + f.a)
        val per = tokens.map { t -> hay.maxOfOrNull { SearchLogic.wordScore(t, it) } ?: 0 }
        if (per.all { it > 0 }) f to per.sum() else null
    }.sortedByDescending { it.second }.map { it.first }
}
